/*
   Get all Nigerian states.
*/

function getNigeriaStates() {

    return Object.keys(
        NIGERIAN_LOCATION_DATA.Nigeria
    );

}


/*
   Get cities belonging to a state.
*/

function getCitiesByState(
    state
) {

    return (
        NIGERIAN_LOCATION_DATA
            .Nigeria
            ?.[state]
            ?.cities || []
    );

}


/*
   Get LGAs belonging to a state.
*/

function getLGAsByState(
    state
) {

    return (
        NIGERIAN_LOCATION_DATA
            .Nigeria
            ?.[state]
            ?.lgas || []
    );

}


