/* =========================================================
   UPDATE WORD COUNTER
========================================================= */

function updateWordCounter() {

    if (
        !bio ||
        !wordCounter
    ) {

        return;

    }


    const text =
        bio.value.trim();


    /*
        Empty description = 0 words.
    */

    if (!text) {

        wordCounter.textContent =
            "0";

        return;

    }


    /*
        Count words separated by whitespace.
    */

    const words =
        text.split(
            /\s+/
        );


    const wordCount =
        words.length;


    wordCounter.textContent =
        wordCount;


    /*
        Highlight counter at the limit.
    */

    const counter =
        document.querySelector(
            ".counter"
        );


    if (counter) {

        counter.classList.toggle(
            "limit-reached",
            wordCount >= 150
        );

    }

}


/* =========================================================
   PROFILE COMPLETION
========================================================= */

function updateCompletion() {

    if (!completionPercent) {
        return;
    }


    let completed =
        0;


    const total =
        12;


    /*
        1. Profile photo
    */

    if (
        profilePhoto &&
        profilePhoto.files.length > 0
    ) {

        completed++;

    }


    /*
        2. Full name
    */

    if (
        fullName &&
        fullName.value.trim()
    ) {

        completed++;

    }


    /*
        3. Phone
    */

    if (
        phone &&
        phone.value.trim()
    ) {

        completed++;

    }


    /*
        4. Primary skill
    */

    if (
        primarySkill &&
        primarySkill.value
    ) {

        completed++;

    }


    /*
        5. Experience
    */

    if (
        experience &&
        experience.value
    ) {

        completed++;

    }


    /*
        6. Starting price
    */

    if (
        price &&
        price.value
    ) {

        completed++;

    }


    /*
        7. State
    */

    if (
        state &&
        state.value
    ) {

        completed++;

    }


    /*
        8. City
    */

    if (
        city &&
        city.value
    ) {

        completed++;

    }


    /*
        9. Description
    */

    if (
        bio &&
        bio.value.trim()
    ) {

        completed++;

    }


    /*
        10–12. Portfolio images
    */

    for (
        let i = 1;
        i <= 3;
        i++
    ) {

        const portfolioInput =
            document.getElementById(
                `portfolio${i}`
            );


        if (
            portfolioInput &&
            portfolioInput.files.length > 0
        ) {

            completed++;

        }

    }


    /*
        Calculate percentage.
    */

    const percentage =
        Math.round(
            (completed / total) * 100
        );


    /*
        Display percentage.
    */

    completionPercent.textContent =
        `${percentage}%`;

}


