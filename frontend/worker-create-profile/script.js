/* =========================================================
   IMAGE PREVIEW
========================================================= */

function previewImage(
    input,
    preview
) {

    /*
        Make sure a file exists.
    */

    if (
        !input ||
        !input.files ||
        !input.files[0]
    ) {

        return;

    }


    const file =
        input.files[0];


    /* =====================================================
       CHECK IMAGE TYPE
    ===================================================== */

    /*
        Make sure the selected file
        is actually an image.
    */

    if (
        !file.type.startsWith(
            "image/"
        )
    ) {

        showModal(

            "error",

            "Invalid Image",

            "Please select a valid PNG, JPG or WEBP image."

        );


        input.value =
            "";

        return;

    }


    /* =====================================================
       CHECK IMAGE SIZE
    ===================================================== */

    /*
        Reject images larger than
        the maximum allowed size.
    */

    if (
        file.size >
        MAX_IMAGE_SIZE
    ) {

        showModal(

            "error",

            "Image Too Large",

            `The selected image is ${formatFileSize(file.size)} MB. ` +
            `Each image must not exceed 5 MB.`

        );


        /*
            Clear the invalid file.

            This also prevents it from
            being uploaded later.
        */

        input.value =
            "";


        /*
            Remove any previous preview.
        */

        if (preview) {

            preview.innerHTML =
                "";

            preview.classList.remove(
                "has-image"
            );

        }


        /*
            Recalculate profile completion.
        */

        updateCompletion();

        return;

    }


    /* =====================================================
       CREATE IMAGE PREVIEW
    ===================================================== */

    const imageURL =
        URL.createObjectURL(
            file
        );


    /*
        Remove old preview content.
    */

    preview.innerHTML =
        "";


    /*
        Create image element.
    */

    const image =
        document.createElement(
            "img"
        );

    image.src =
        imageURL;

    image.alt =
        "Selected image preview";


    /*
        Add image to preview.
    */

    preview.appendChild(
        image
    );


    /*
        Mark preview as containing
        an image.
    */

    preview.classList.add(
        "has-image"
    );

}


