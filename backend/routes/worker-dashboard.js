/* =========================================================
   1. IMPORT EXPRESS
========================================================= */

const express = require("express");


/* =========================================================
   2. IMPORT DASHBOARD CONTROLLER
========================================================= */

const {
    getWorkerDashboard,
    verifyWorkerPhone,
    logoutWorker
} = require("../controllers/worker-dashboard");


/* =========================================================
   3. CREATE ROUTER
========================================================= */

const router = express.Router();


/* =========================================================
   4. WORKER DASHBOARD
========================================================= */

router.get(
    "/dashboard",
    getWorkerDashboard
);


/* =========================================================
   5. SEND PHONE OTP
========================================================= */

router.post(
    "/send-phone-otp",
    verifyWorkerPhone
);


/* =========================================================
   6. WORKER LOGOUT
========================================================= */

router.post(
    "/logout",
    logoutWorker
);


/* =========================================================
   7. EXPORT ROUTER
========================================================= */

module.exports = router;