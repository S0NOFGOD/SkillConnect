/* =========================================================
   1. IMPORT EXPRESS
========================================================= */

const express =
    require("express");



/* =========================================================
   2. CREATE EXPRESS ROUTER
========================================================= */

const router =
    express.Router();



/* =========================================================
   3. IMPORT CLIENT WORKER DETAILS CONTROLLER
========================================================= */

const {

    getWorkerDetails

} = require(
    "../controllers/client-worker-details"
);



/* =========================================================
   4. GET WORKER DETAILS
========================================================= */

router.get(

    "/:workerId",

    getWorkerDetails

);



/* =========================================================
   5. EXPORT ROUTER
========================================================= */

module.exports =
    router;